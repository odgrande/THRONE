const DICTS = { en, pcm, yo, ha, ig };
const KEY = 'throne.lang';

function saved() {
  try {
    const value = localStorage.getItem(KEY);
    return DICTS[value] ? value : null;
  } catch {
    return null;
  }
}

let lang = saved() ?? 'en';
document.documentElement.lang = lang === 'pcm' ? 'pcm' : lang;

export const currentLang = () => lang;

export function setLang(id) {
  if (!DICTS[id] || id === lang) return;
  try {
    localStorage.setItem(KEY, id);
  } catch {
    // Storage blocked: the choice lasts for this page view only.
  }
  // Reload so every string on the page, including ones computed once, switches together.
  window.location.reload();
}

export function t(key, vars) {
  const text = DICTS[lang][key] ?? en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`)) : text;
}
